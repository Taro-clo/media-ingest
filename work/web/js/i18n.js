export const LOCALES = { 'zh-CN': zh, 'en': en };

let current = 'zh-CN';

export function setLocale(locale) {
  if (LOCALES[locale]) current = locale;
  return current;
}

export function getLocale() {
  return current;
}

export function availableLocales() {
  return Object.keys(LOCALES);
}

/**
 * 取文案。未命中当前语言时回退 zh-CN；仍未命中时返回 key 本身（便于发现遗漏）。
 * vars 用于替换 {name} 形式的占位符。
 */
export function t(key, vars) {
  const dict = LOCALES[current] || zh;
  let text = dict[key];
  if (text === undefined || text === null || text === '') text = zh[key];
  if (text === undefined || text === null) return key;
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, function (m, name) {
    const v = vars[name];
    return v === undefined || v === null ? m : String(v);
  });
}

/** 供自检脚本与调试使用：判断文案是否存在。 */
export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(zh, key);
}

export function allKeys() {
  return Object.keys(zh);
}
